/**
 * Expo config plugin: applies the user's in-app theme choice to the native
 * window BEFORE the splash screen renders, on both platforms.
 *
 * Why this is needed:
 *   The app lets users force light/dark independently of the system
 *   appearance. That choice lives in AsyncStorage and is applied at JS
 *   runtime via Appearance.setColorScheme — which means on every cold start
 *   the native splash screen (and the window behind it) still follows the
 *   SYSTEM appearance until the JS bundle loads and reads storage. A user
 *   who forced dark mode on a light-mode device boots into a white splash
 *   that then flips to dark: the "splash blink".
 *
 *   iOS: the JS side mirrors the choice into NSUserDefaults via React
 *   Native's `Settings` API (key: `pegadaThemeOverride`, see
 *   src/contexts/theme-provider.tsx). This plugin injects a snippet into
 *   AppDelegate.swift, right after the UIWindow is created and before
 *   startReactNative shows the splash, that reads the key and sets
 *   `overrideUserInterfaceStyle` accordingly.
 *
 *   Android: React Native's `Settings` API has no Android implementation
 *   (it's a no-op stub there), so the JS side mirrors the choice into
 *   SharedPreferences via the local `pegada-theme-override` native module
 *   instead (same key, different store — see modules/pegada-theme-override
 *   and theme-provider.tsx). This plugin injects a snippet into
 *   MainApplication.kt's onCreate, right after super.onCreate() and before
 *   any Activity/splash is created, that reads the SharedPreferences value
 *   and calls AppCompatDelegate.setDefaultNightMode. Android resolves
 *   values-night resources (the splash background among them) off that
 *   night mode, so setting it this early is enough for the splash to pick
 *   the right variant from the first frame.
 *
 *   On both platforms, the dark splash background/icon variants already
 *   exist (generated by expo prebuild from the *.splash.dark config), so
 *   overriding the window's style/night mode is enough for the splash — and
 *   everything after it — to resolve the right colors from the first frame.
 *   It also makes React Native's Appearance module report the forced scheme
 *   immediately, so the first JS render is already themed correctly.
 *
 *   Values "dark" and "light" force the style; "system" (or no key, e.g.
 *   fresh installs and users who never forced a theme) leaves the window
 *   following the system appearance — exactly today's behavior.
 *
 * The edits live in `./initial-theme-override` so they can be tested; this
 * file is only the wiring.
 */
const { withAppDelegate, withMainApplication } = require("expo/config-plugins");

const {
  applyIOSThemeOverride,
  applyAndroidThemeOverride,
} = require("./initial-theme-override");

const withInitialThemeOverride = (config) => {
  config = withAppDelegate(config, (modConfig) => {
    modConfig.modResults.contents = applyIOSThemeOverride(
      modConfig.modResults,
    );
    return modConfig;
  });

  return withMainApplication(config, (modConfig) => {
    modConfig.modResults.contents = applyAndroidThemeOverride(
      modConfig.modResults,
    );
    return modConfig;
  });
};

module.exports = withInitialThemeOverride;
